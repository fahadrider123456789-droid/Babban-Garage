app = Flask(__name__)

app.secret_key = (
    os.environ.get("SECRET_KEY") or secrets.token_hex(32)
)

app.config.update(
    SESSION_COOKIE_HTTPONLY=True,
    SESSION_COOKIE_SAMESITE="Lax",
    SESSION_COOKIE_SECURE=os.environ.get("HTTPS_ONLY") == "1",
    MAX_CONTENT_LENGTH=1024 * 1024,
)

DATABASE_URL = os.environ.get("DATABASE_URL", "").strip()

if not DATABASE_URL:
    raise RuntimeError(
        "Render Environment mein DATABASE_URL set karo."
    )


def db():
    return psycopg.connect(
        DATABASE_URL,
        row_factory=dict_row,
        connect_timeout=20,
    )


def init_db():
    schema = [
        """
        CREATE TABLE IF NOT EXISTS users (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL,
            username TEXT UNIQUE NOT NULL,
            password TEXT NOT NULL,
            role TEXT NOT NULL
                CHECK (role IN ('owner', 'staff')),
            active INTEGER DEFAULT 1
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS customers (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL,
            phone TEXT NOT NULL,
            address TEXT DEFAULT ''
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS vehicles (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            customer_id INTEGER NOT NULL REFERENCES customers(id),
            registration TEXT UNIQUE NOT NULL,
            model TEXT NOT NULL
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS jobs (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            vehicle_id INTEGER NOT NULL REFERENCES vehicles(id),
            mechanic_id INTEGER REFERENCES users(id),
            problem TEXT NOT NULL,
            status TEXT DEFAULT 'Naya',
            created TEXT NOT NULL
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS stock (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL,
            code TEXT UNIQUE NOT NULL,
            quantity INTEGER NOT NULL CHECK (quantity >= 0),
            price BIGINT NOT NULL CHECK (price >= 0)
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS bills (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            job_id INTEGER UNIQUE REFERENCES jobs(id),
            customer_id INTEGER NOT NULL REFERENCES customers(id),
            description TEXT NOT NULL,
            total BIGINT NOT NULL CHECK (total > 0),
            created TEXT NOT NULL
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS payments (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            bill_id INTEGER NOT NULL REFERENCES bills(id),
            amount BIGINT NOT NULL CHECK (amount > 0),
            method TEXT NOT NULL,
            reference TEXT,
            created TEXT NOT NULL
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS expenses (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            description TEXT NOT NULL,
            amount BIGINT NOT NULL CHECK (amount > 0),
            created TEXT NOT NULL
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS attendance (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id INTEGER NOT NULL REFERENCES users(id),
            day TEXT NOT NULL,
            status TEXT NOT NULL,
            UNIQUE (user_id, day)
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS salary_entries (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id INTEGER NOT NULL REFERENCES users(id),
            kind TEXT NOT NULL
                CHECK (kind IN ('Earned', 'Payment', 'Advance')),
            amount BIGINT NOT NULL CHECK (amount > 0),
            note TEXT NOT NULL,
            created TEXT NOT NULL
        )
        """,
    ]

    with db() as c:
        c.execute("SELECT pg_advisory_xact_lock(724103826)")

        for statement in schema:
            c.execute(statement)

        owner = c.execute(
            "SELECT id FROM users WHERE role='owner' LIMIT 1"
        ).fetchone()

        if not owner:
            password = os.environ.get("OWNER_PASSWORD", "")

            if len(password) < 12:
                raise RuntimeError(
                    "First startup ke liye OWNER_PASSWORD "
                    "minimum 12 characters hona chahiye."
                )

            c.execute(
                """
                INSERT INTO users (name, username, password, role)
                VALUES (%s, %s, %s, %s)
                """,
                (
                    "Owner",
                    "owner",
                    generate_password_hash(password),
                    "owner",
                ),
            )


init_db()


def money(value):
    try:
        amount = Decimal(value)

        if (
            not amount.is_finite()
            or amount <= 0
            or amount > Decimal("100000000")
        ):
            raise ValueError("Invalid amount")

        if amount != amount.quantize(Decimal("0.01")):
            raise ValueError("Use maximum two decimal places")

        return int(amount * 100)

    except (InvalidOperation, TypeError):
        raise ValueError("Invalid amount") from None


def auth(owner=False):
    def deco(function):
        @wraps(function)
        def run(*args, **kwargs):
            with db() as c:
                user = c.execute(
                    """
                    SELECT * FROM users
                    WHERE id=%s AND active=1
                    """,
                    (session.get("uid"),),
                ).fetchone()

            if not user:
                return redirect("/login")

            if owner and user["role"] != "owner":
                abort(403)

            return function(*args, **kwargs)

        return run

    return deco


@app.before_request
def csrf():
    session.setdefault("csrf", secrets.token_hex(32))

    if request.method == "POST":
        expected = session["csrf"]
        supplied = request.form.get("csrf", "")

        if not secrets.compare_digest(
            expected.encode("utf-8"),
            supplied.encode("utf-8"),
        ):
            abort(403)


@app.template_filter("inr")
def inr(value):
    return f"{(value or 0) / 100:,.2f}"


@app.template_filter("day")
def day(value):
    return date.fromisoformat(value).strftime("%d/%m/%Y")


@app.route("/login", methods=["GET", "POST"])
def login():
    if request.method == "POST":
        with db() as c:
            user = c.execute(
                """
                SELECT * FROM users
                WHERE username=%s AND active=1
                """,
                (request.form.get("username"),),
            ).fetchone()

        if user and check_password_hash(
            user["password"],
            request.form.get("password", ""),
        ):
            session.clear()
            session["uid"] = user["id"]
            return redirect("/")

        flash("Login galat hai")

    return render_template("login.html")


@app.post("/logout")
def logout():
    session.clear()
    return redirect("/login")


@app.get("/")
@auth()
def home():
    with db() as c:
        user = c.execute(
            "SELECT * FROM users WHERE id=%s",
            (session["uid"],),
        ).fetchone()

        owner = user["role"] == "owner"

        jobs_query = """
            SELECT j.*, v.registration, u.name AS mechanic
            FROM jobs j
            JOIN vehicles v ON v.id=j.vehicle_id
            LEFT JOIN users u ON u.id=j.mechanic_id
        """

        if owner:
            jobs = c.execute(
                jobs_query + " ORDER BY j.id DESC"
            ).fetchall()
        else:
            jobs = c.execute(
                jobs_query
                + " WHERE j.mechanic_id=%s ORDER BY j.id DESC",
                (user["id"],),
            ).fetchall()

        data = {}

        if owner:
            for table in [
                "customers",
                "vehicles",
                "stock",
                "users",
                "expenses",
                "attendance",
                "salary_entries",
            ]:
                data[table] = c.execute(
                    "SELECT * FROM " + table + " ORDER BY id DESC"
                ).fetchall()

            data["bills"] = c.execute(
                """
                SELECT b.*, c.name,
                    COALESCE(
                        (
                            SELECT SUM(p.amount)
                            FROM payments p
                            WHERE p.bill_id=b.id
                        ),
                        0
                    ) AS paid
                FROM bills b
                JOIN customers c ON c.id=b.customer_id
                ORDER BY b.id DESC
                """
            ).fetchall()

            today = date.today().isoformat()

            data["billing"] = c.execute(
                """
                SELECT COALESCE(SUM(total), 0) AS value
                FROM bills WHERE created=%s
                """,
                (today,),
            ).fetchone()["value"]

            data["collected"] = c.execute(
                """
                SELECT COALESCE(SUM(amount), 0) AS value
                FROM payments WHERE created=%s
                """,
                (today,),
            ).fetchone()["value"]

            data["spent"] = c.execute(
                """
                SELECT COALESCE(SUM(amount), 0) AS value
                FROM expenses WHERE created=%s
                """,
                (today,),
            ).fetchone()["value"]

            data["due"] = sum(
                bill["total"] - bill["paid"]
                for bill in data["bills"]
            )

        else:
            data["attendance"] = c.execute(
                """
                SELECT * FROM attendance
                WHERE user_id=%s ORDER BY day DESC
                """,
                (user["id"],),
            ).fetchall()

            data["salary_entries"] = c.execute(
                """
                SELECT * FROM salary_entries
                WHERE user_id=%s ORDER BY id DESC
                """,
                (user["id"],),
            ).fetchall()

        data["salary_balance"] = (
            sum(
                entry["amount"]
                if entry["kind"] == "Earned"
                else -entry["amount"]
                for entry in data["salary_entries"]
            )
            if not owner
            else None
        )

    return render_template(
        "home.html",
        u=user,
        owner=owner,
        jobs=jobs,
        d=data,
    )


@app.post("/add/<kind>")
@auth(owner=True)
def add(kind):
    f = request.form
    today = date.today().isoformat()

    try:
        with db() as c:
            if kind == "customer":
                c.execute(
                    """
                    INSERT INTO customers (name, phone, address)
                    VALUES (%s, %s, %s)
                    """,
                    (
                        f["name"].strip(),
                        f["phone"].strip(),
                        f.get("address", ""),
                    ),
                )

            elif kind == "vehicle":
                c.execute(
                    """
                    INSERT INTO vehicles
                        (customer_id, registration, model)
                    VALUES (%s, %s, %s)
                    """,
                    (
                        int(f["customer_id"]),
                        f["registration"].upper().replace(" ", ""),
                        f["model"],
                    ),
                )

            elif kind == "job":
                mechanic_id = (
                    int(f["mechanic_id"])
                    if f.get("mechanic_id")
                    else None
                )

                if mechanic_id:
                    mechanic = c.execute(
                        """
                        SELECT id FROM users
                        WHERE id=%s AND role='staff' AND active=1
                        """,
                        (mechanic_id,),
                    ).fetchone()

                    if not mechanic:
                        raise ValueError("Active mechanic chuno")

                c.execute(
                    """
                    INSERT INTO jobs
                        (vehicle_id, mechanic_id, problem, created)
                    VALUES (%s, %s, %s, %s)
                    """,
                    (
                        int(f["vehicle_id"]),
                        mechanic_id,
                        f["problem"],
                        today,
                    ),
                )

            elif kind == "stock":
                c.execute(
                    """
                    INSERT INTO stock (name, code, quantity, price)
                    VALUES (%s, %s, %s, %s)
                    """,
                    (
                        f["name"],
                        f["code"],
                        int(f["quantity"]),
                        money(f["price"]),
                    ),
                )

            elif kind == "bill":
                job_id = (
                    int(f["job_id"]) if f.get("job_id") else None
                )
                customer_id = int(f["customer_id"])

                if job_id:
                    row = c.execute(
                        """
                        SELECT v.customer_id
                        FROM jobs j
                        JOIN vehicles v ON v.id=j.vehicle_id
                        WHERE j.id=%s
                        """,
                        (job_id,),
                    ).fetchone()

                    if (
                        not row
                        or row["customer_id"] != customer_id
                    ):
                        raise ValueError(
                            "Job aur customer match nahi karte"
                        )

                c.execute(
                    """
                    INSERT INTO bills
                        (job_id, customer_id, description,
                         total, created)
                    VALUES (%s, %s, %s, %s, %s)
                    """,
                    (
                        job_id,
                        customer_id,
                        f["description"],
                        money(f["total"]),
                        today,
                    ),
                )

            elif kind == "payment":
                bill_id = int(f["bill_id"])
                amount = money(f["amount"])

                bill = c.execute(
                    """
                    SELECT total FROM bills
                    WHERE id=%s FOR UPDATE
                    """,
                    (bill_id,),
                ).fetchone()

                if not bill:
                    raise ValueError("Bill nahi mila")

                paid = c.execute(
                    """
                    SELECT COALESCE(SUM(amount), 0) AS value
                    FROM payments WHERE bill_id=%s
                    """,
                    (bill_id,),
                ).fetchone()["value"]

                if amount > bill["total"] - paid:
                    raise ValueError(
                        "Payment baaki amount se zyada hai"
                    )

                if f["method"] not in [
                    "Cash", "UPI", "Bank transfer"
                ]:
                    raise ValueError("Invalid payment method")

                c.execute(
                    """
                    INSERT INTO payments
                        (bill_id, amount, method, reference, created)
                    VALUES (%s, %s, %s, %s, %s)
                    """,
                    (
                        bill_id,
                        amount,
                        f["method"],
                        f.get("reference", ""),
                        today,
                    ),
                )

            elif kind == "expense":
                c.execute(
                    """
                    INSERT INTO expenses
                        (description, amount, created)
                    VALUES (%s, %s, %s)
                    """,
                    (
                        f["description"],
                        money(f["amount"]),
                        today,
                    ),
                )

            elif kind == "staff":
                if len(f["password"]) < 12:
                    raise ValueError(
                        "Password minimum 12 characters"
                    )

                c.execute(
                    """
                    INSERT INTO users
                        (name, username, password, role)
                    VALUES (%s, %s, %s, 'staff')
                    """,
                    (
                        f["name"],
                        f["username"],
                        generate_password_hash(f["password"]),
                    ),
                )

            elif kind in ["attendance", "salary"]:
                user_id = int(f["user_id"])

                staff = c.execute(
                    """
                    SELECT id FROM users
                    WHERE id=%s AND role='staff'
                    """,
                    (user_id,),
                ).fetchone()

                if not staff:
                    raise ValueError("Staff chuno")

                if kind == "attendance":
                    date.fromisoformat(f["day"])

                    if f["status"] not in [
                        "Present", "Absent", "Half-day", "Leave"
                    ]:
                        raise ValueError("Invalid status")

                    c.execute(
                        """
                        INSERT INTO attendance
                            (user_id, day, status)
                        VALUES (%s, %s, %s)
                        ON CONFLICT (user_id, day)
                        DO UPDATE SET status=EXCLUDED.status
                        """,
                        (
                            user_id,
                            f["day"],
                            f["status"],
                        ),
                    )

                else:
                    c.execute(
                        """
                        INSERT INTO salary_entries
                            (user_id, kind, amount, note, created)
                        VALUES (%s, %s, %s, %s, %s)
                        """,
                        (
                            user_id,
                            f["kind"],
                            money(f["amount"]),
                            f["note"],
                            today,
                        ),
                    )

            elif kind == "deactivate":
                c.execute(
                    """
                    UPDATE users SET active=0
                    WHERE id=%s AND role='staff'
                    """,
                    (int(f["user_id"]),),
                )

            elif kind == "status":
                if f["status"] not in [
                    "Naya",
                    "Checking",
                    "Kaam Chal Raha Hai",
                    "Parts Ka Intezaar",
                    "Ready",
                    "Delivered",
                    "Cancelled",
                ]:
                    raise ValueError("Invalid status")

                c.execute(
                    "UPDATE jobs SET status=%s WHERE id=%s",
                    (f["status"], int(f["job_id"])),
                )

            else:
                abort(404)

        flash("Save ho gaya")

    except (ValueError, KeyError, psycopg.IntegrityError):
        flash(
            "Save nahi hua: fields check karo. "
            "Duplicate record, galat reference ya "
            "invalid amount ho sakta hai."
        )

    return redirect("/")


@app.get("/bill/<int:bid>")
@auth(owner=True)
def bill(bid):
    with db() as c:
        bill_record = c.execute(
            """
            SELECT b.*, c.name, c.phone
            FROM bills b
            JOIN customers c ON c.id=b.customer_id
            WHERE b.id=%s
            """,
            (bid,),
        ).fetchone()

        if not bill_record:
            abort(404)

        payments = c.execute(
            """
            SELECT * FROM payments
            WHERE bill_id=%s ORDER BY id
            """,
            (bid,),
        ).fetchall()

    return render_template(
        "bill.html",
        b=bill_record,
        p=payments,
        paid=sum(payment["amount"] for payment in payments),
    )


